import type { DeskRole } from './desk';

/**
 * Staff package T8: «Инструкции» for the worker, in plain Russian, one
 * screen. It opens from the button on the desk (the owner's «Инструкции»
 * page is the owner's alone). The common part is the same for everybody,
 * then one part for the role. Numbers are the starting ones; the desk
 * header shows the real ones from the settings.
 */
export const DESK_GUIDE_COMMON = `## Как устроен ваш стол

У вас **одна страница** и вкладки сверху. Больше ничего открывать не нужно.

1. Нажмите **«Следующий»**. Система даст вам один элемент и закрепит его за вами. Остальные сотрудники его не увидят.
2. Работайте: откройте, проверьте, решите. Пока вы заняты, элемент ваш.
3. Закончили — нажмите «Следующий» снова.

## Если нужно отвлечься

- **«Отпустить»** на вкладке «Мои» — элемент уйдёт следующему сотруднику.
- Нет движения на странице несколько минут или пропала связь — элемент вернётся в очередь сам. За полминуты до этого придёт предупреждение.
- Статус «отошёл» — новое вам не дают, взятое остаётся у вас до конца срока.

## Ваш рейтинг и оплата

На вкладке «Мой рейтинг» видно оценку за 30 дней и из чего она сложилась. Это только ваши цифры, коллеги их не видят. Если решений ещё мало, будет написано «мало данных» — это не плохо.

## Если вас обидели

Кнопка **«Обжаловать главного»** (если она есть) отправляет жалобу только владельцу. Главный её не увидит. Можно отправить анонимно.`;

