/** States whose code or name contains [q] (case-insensitive). */
export function searchStates(q: string): typeof US_STATES {
  const t = q.trim().toLowerCase();
  if (!t) return US_STATES;
  return US_STATES.filter((s) => s.code.toLowerCase().includes(t) || s.name.toLowerCase().includes(t));
}

/** "" for every state, "из штата IL", "в 5 штатах: IL, NY, CA, TX, FL",
 * long lists cut after [max] codes ("… и ещё 12"). */
export function statesText(codes: readonly string[], max = 8): string {
  if (codes.length === 0) return '';
  if (codes.length === 1) return `из штата ${codes[0]}`;
  const shown = codes.slice(0, max).join(', ');
  const rest = codes.length - max;
  return `в ${codes.length} ${plural(codes.length, 'штате', 'штатах', 'штатах')}: ${shown}${rest > 0 ? ` и ещё ${rest}` : ''}`;
}
