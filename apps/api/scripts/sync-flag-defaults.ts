// `npm run flags:sync` — writes the app's first-paint flag defaults
// (apps/mobile/lib/core/feature_flags/default_feature_flags.dart) from
// FLAG_CATALOG, the one list of feature flags. `--check` only compares.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { FLAG_CATALOG } from '../src/modules/feature-flags/flag-catalog';

const FILE = join(
  __dirname,
  '../../mobile/lib/core/feature_flags/default_feature_flags.dart',
);
const BEGIN = '  // <flags:begin> generated by `npm run flags:sync` from FLAG_CATALOG';
const END = '  // <flags:end>';

export function renderFlagBlock(): string {
  const rows = FLAG_CATALOG.filter((f) => f.app).map(
    (f) => `  '${f.key}': ${f.enabled},`,
  );
  return [BEGIN, ...rows, END].join('\n');
}

export function applyBlock(source: string): string {
  const a = source.indexOf(BEGIN);
  const b = source.indexOf(END);
  if (a < 0 || b < 0) throw new Error('flag markers missing in the Dart file');
  return source.slice(0, a) + renderFlagBlock() + source.slice(b + END.length);
}

if (require.main === module) {
  const current = readFileSync(FILE, 'utf8');
  const next = applyBlock(current);
  if (process.argv.includes('--check')) {
    if (next !== current) {
      process.stderr.write('default_feature_flags.dart is stale: run npm run flags:sync\n');
      process.exit(1);
    }
  } else {
    writeFileSync(FILE, next);
    process.stdout.write('default_feature_flags.dart updated\n');
  }
}
