-- Deal record 2026-10-27 (docs/architecture/DEAL_RECORD_PLAN_2026-10-27.md):
-- «Запись о заключении сделки» — rich payment terms on bids and the record
-- both parties sign before a bid is really accepted. Everything here is
-- EMPTY and unused until the admin switches `deal_record.enabled` /
-- `bids.rich_terms_enabled` (both off) are turned on.
--  - bids / bid_offers get a nullable `payment_terms` jsonb (no default, no
--    rewrite: PostgreSQL adds a nullable column as metadata only).
--  - one new table deal_records (case family, shard_id filled by the same
--    trigger as every other sharded table).
-- Expand-only: the running release never reads these columns / tables.
SET LOCAL lock_timeout = '5s';

-- CreateEnum
CREATE TYPE "deal_record_status" AS ENUM ('preparing', 'awaiting_signatures', 'sealing', 'sealed', 'declined', 'failed');

-- AlterTable (nullable, no default -> no table rewrite)
ALTER TABLE "bids" ADD COLUMN "payment_terms" JSONB;
ALTER TABLE "bid_offers" ADD COLUMN "payment_terms" JSONB;

-- CreateTable
CREATE TABLE "deal_records" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "case_id" UUID NOT NULL,
    "bid_id" UUID NOT NULL,
    "accepted_by" "party_role" NOT NULL,
    "initiator_id" UUID NOT NULL,
    "status" "deal_record_status" NOT NULL DEFAULT 'preparing',
    "snapshot" JSONB NOT NULL,
    "snapshot_sha256" VARCHAR(64) NOT NULL,
    "record_code" VARCHAR(24) NOT NULL,
    "text_version" INTEGER NOT NULL DEFAULT 0,
    "sign_request_id" UUID,
    "unsigned_file_id" UUID,
    "sealed_file_id" UUID,
    "sealed_sha256" VARCHAR(64),
    "agreement_file_id" UUID,
    "declined_by" UUID,
    "decline_reason" VARCHAR(300),
    "failed_reason" VARCHAR(300),
    "sealed_at" TIMESTAMPTZ,
    "declined_at" TIMESTAMPTZ,
    "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "shard_id" SMALLINT NOT NULL DEFAULT 0,

    CONSTRAINT "deal_records_pkey" PRIMARY KEY ("id")
);

-- Indexes on the table created in this migration (empty, no lock issue).
CREATE UNIQUE INDEX "deal_records_sign_request_id_key" ON "deal_records"("sign_request_id");
CREATE INDEX "deal_records_case_id_created_at_idx" ON "deal_records"("case_id", "created_at");
CREATE INDEX "deal_records_bid_id_idx" ON "deal_records"("bid_id");
CREATE INDEX "deal_records_status_idx" ON "deal_records"("status");

-- AddForeignKey (the referenced tables are only read: SHARE ROW EXCLUSIVE
-- on cases / bids / case_sign_requests for the time of the ADD, no rewrite).
ALTER TABLE "deal_records" ADD CONSTRAINT "deal_records_case_id_fkey" FOREIGN KEY ("case_id") REFERENCES "cases"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "deal_records" ADD CONSTRAINT "deal_records_bid_id_fkey" FOREIGN KEY ("bid_id") REFERENCES "bids"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "deal_records" ADD CONSTRAINT "deal_records_sign_request_id_fkey" FOREIGN KEY ("sign_request_id") REFERENCES "case_sign_requests"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "deal_records" ADD CONSTRAINT "deal_records_unsigned_file_id_fkey" FOREIGN KEY ("unsigned_file_id") REFERENCES "files"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "deal_records" ADD CONSTRAINT "deal_records_sealed_file_id_fkey" FOREIGN KEY ("sealed_file_id") REFERENCES "files"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "deal_records" ADD CONSTRAINT "deal_records_agreement_file_id_fkey" FOREIGN KEY ("agreement_file_id") REFERENCES "files"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- shard_id trigger, the same lawbid_shard_fill() every sharded table has
-- (20261024150000_shard_map_and_triggers). Generated by
-- `npx ts-node --transpile-only scripts/generate-shard-trigger-migration.ts`;
-- src/sharding/shard-trigger-migration.spec.ts checks the line.
DROP TRIGGER IF EXISTS "deal_records_shard_fill" ON "deal_records";
CREATE TRIGGER "deal_records_shard_fill" BEFORE INSERT ON "deal_records" FOR EACH ROW WHEN (NEW."shard_id" = 0) EXECUTE FUNCTION lawbid_shard_fill('parent', 'case_id', 'cases');
