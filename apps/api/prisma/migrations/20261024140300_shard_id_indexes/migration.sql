-- transaction, where CONCURRENTLY is not allowed. Safe now because the
-- tables are small (a plain build blocks writes only while it runs); if
-- this ever has to be re-applied to a large database, create the same
-- indexes CONCURRENTLY by hand first (IF NOT EXISTS makes this a no-op).
