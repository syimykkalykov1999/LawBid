-- Owner row 87 (hotline plan PR 4): the billing record of a hotline call.
-- One row per request; time counts from «Взять» (answered_at). The voice
-- is the ordinary 1:1 call (call_id, a bare pointer: calls live in the case
-- family). Audio only, never recorded. Expand-only: a new table.
CREATE TABLE "hotline_calls" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "request_id" UUID NOT NULL,
    "call_id" UUID,
    "client_id" UUID NOT NULL,
    "attorney_id" UUID NOT NULL,
    "state_code" VARCHAR(2) NOT NULL,
    "practice_area" VARCHAR(64) NOT NULL,
    "answered_at" TIMESTAMPTZ NOT NULL,
    "ended_at" TIMESTAMPTZ,
    "end_reason" VARCHAR(32),
    "duration_sec" INTEGER,
    "conversation_id" UUID,
    "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "shard_id" SMALLINT NOT NULL DEFAULT 0,

    CONSTRAINT "hotline_calls_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "hotline_calls_request_id_key" ON "hotline_calls"("request_id");
CREATE INDEX "hotline_calls_attorney_id_answered_at_idx" ON "hotline_calls"("attorney_id", "answered_at" DESC);
CREATE INDEX "hotline_calls_client_id_answered_at_idx" ON "hotline_calls"("client_id", "answered_at" DESC);

-- shard_id trigger, the same lawbid_shard_fill() every sharded table has
-- (20261024150000_shard_map_and_triggers). Generated by
-- `npx ts-node --transpile-only scripts/generate-shard-trigger-migration.ts`;
-- src/sharding/shard-trigger-migration.spec.ts checks the line.
DROP TRIGGER IF EXISTS "hotline_calls_shard_fill" ON "hotline_calls";
CREATE TRIGGER "hotline_calls_shard_fill" BEFORE INSERT ON "hotline_calls" FOR EACH ROW WHEN (NEW."shard_id" = 0) EXECUTE FUNCTION lawbid_shard_fill('owner', 'attorney_id', '');
