-- B-c7 (2026-11-09): the journal of unfollows, the tombstones that
-- GET /users/me/following?updatedSince answers in meta.deletedIds (as the
-- groups list does). Expand-only: a new table nobody reads yet.
CREATE TABLE "follow_tombstones" (
  "follower_id" UUID NOT NULL,
  "followee_id" UUID NOT NULL,
  "deleted_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "shard_id" SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT "follow_tombstones_pkey" PRIMARY KEY ("follower_id", "followee_id"),
  CONSTRAINT "follow_tombstones_follower_id_fkey" FOREIGN KEY ("follower_id") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "follow_tombstones_follower_id_deleted_at_idx" ON "follow_tombstones"("follower_id", "deleted_at");
CREATE INDEX "follow_tombstones_deleted_at_idx" ON "follow_tombstones"("deleted_at");

-- shard_id trigger, the same lawbid_shard_fill() every sharded table has
-- (20261024150000_shard_map_and_triggers). Generated by
-- `npx ts-node --transpile-only scripts/generate-shard-trigger-migration.ts`;
-- src/sharding/shard-trigger-migration.spec.ts checks the line.
DROP TRIGGER IF EXISTS "follow_tombstones_shard_fill" ON "follow_tombstones";
CREATE TRIGGER "follow_tombstones_shard_fill" BEFORE INSERT ON "follow_tombstones" FOR EACH ROW WHEN (NEW."shard_id" = 0) EXECUTE FUNCTION lawbid_shard_fill('owner', 'follower_id', '');
