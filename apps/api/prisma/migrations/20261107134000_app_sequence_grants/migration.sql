-- Deploy safety audit 2026-10-27 (docs/dev/DEPLOY_SAFETY_AUDIT_2026-10-27.md).
-- In production the API connects as `lawbid_app`; the baseline gave it
-- SELECT/INSERT/UPDATE/DELETE on TABLES (now and by default) but nothing on
-- SEQUENCES. A SERIAL/BIGSERIAL default calls nextval(), which needs USAGE
-- on the sequence, so every insert into these tables fails in production
-- with "permission denied for sequence" while CI (superuser) stays green:
--   search_query_log / search_clicks (every search is logged and the
--   result-click endpoint awaits the insert -> 500 for the user today),
--   search_outbox (every users/cases/posts write once search.engine is not
--   'postgres' — the trigger inserts there), shard_change_log (shard move),
--   staff author_alias (staff package).
-- Identity columns are not affected (no sequence privilege is checked).
-- Verified on PostgreSQL 16 (2026-10-27): BIGSERIAL insert as a role with
-- table INSERT only -> "permission denied for sequence"; after this GRANT ->
-- works; GENERATED BY DEFAULT AS IDENTITY -> works without it.
-- Grants only: no table lock, no rewrite, safe for the running release.
SET LOCAL lock_timeout = '5s';

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'lawbid_app') THEN
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO lawbid_app;
    -- Sequences the migrator creates from now on.
    ALTER DEFAULT PRIVILEGES IN SCHEMA public
      GRANT USAGE, SELECT ON SEQUENCES TO lawbid_app;
  END IF;
END $$;
