-- Groups WhatsApp parity (reactions): one emoji per person per group
-- message, the same shape as message_reactions of 1:1 chats. Expand-only:
-- a new table nobody reads yet; the running release ignores it.
CREATE TABLE "chat_group_message_reactions" (
  "message_id" UUID NOT NULL,
  "group_id" UUID NOT NULL,
  "user_id" UUID NOT NULL,
  "emoji" VARCHAR(16) NOT NULL,
  "created_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "shard_id" SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT "chat_group_message_reactions_pkey" PRIMARY KEY ("message_id", "user_id"),
  -- Like chat_group_polls: (group_id, id) is the message's key, so only
  -- the group's own hash partition is read.
  CONSTRAINT "chat_group_message_reactions_group_id_message_id_fkey" FOREIGN KEY ("group_id", "message_id") REFERENCES "chat_group_messages"("group_id", "id") ON DELETE CASCADE ON UPDATE CASCADE
);
-- Anonymization / data export find a person's reactions by user.
CREATE INDEX "chat_group_message_reactions_user_id_idx" ON "chat_group_message_reactions"("user_id");

-- shard_id trigger, the same lawbid_shard_fill() every sharded table has
-- (20261024150000_shard_map_and_triggers). Generated by
-- `npx ts-node --transpile-only scripts/generate-shard-trigger-migration.ts`;
-- src/sharding/shard-trigger-migration.spec.ts checks the line.
DROP TRIGGER IF EXISTS "chat_group_message_reactions_shard_fill" ON "chat_group_message_reactions";
CREATE TRIGGER "chat_group_message_reactions_shard_fill" BEFORE INSERT ON "chat_group_message_reactions" FOR EACH ROW WHEN (NEW."shard_id" = 0) EXECUTE FUNCTION lawbid_shard_fill('parent', 'group_id', 'chat_groups');
