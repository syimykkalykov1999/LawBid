-- Shard-ready step 2 (docs/architecture/SHARDING_READY.md §4, §7), part 1/4.
-- Adds `shard_id smallint` to every table of the case / user / content
-- families (the list lives in src/sharding/shard-manifest.ts). Expand-only,
-- no behaviour change.
--
-- Lock safety (Postgres 16): `ADD COLUMN` without a default and
-- `SET DEFAULT <constant>` are metadata-only (no table rewrite, no scan).
-- The column is created NULLable and the default 0 is set at once so rows
-- inserted by the still-running old API during the roll-out get 0, not
-- NULL (the backfill in part 2 only touches NULL rows, i.e. legacy rows).
-- lock_timeout makes a blocked ALTER fail fast (and the deploy retry)
-- instead of queueing behind a long transaction and blocking every query
-- on the table.
SET LOCAL lock_timeout = '5s';

