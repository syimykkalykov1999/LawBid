-- Experiments + ranking_events (owner 2026-10-25, docs/architecture/EXPERIMENTS.md).
-- migration-safety: contract the drop statement only removes expired partitions of ranking_events, a table created in this same migration; no earlier release reads it.

CREATE TABLE "experiments" (
  "id"                UUID NOT NULL DEFAULT gen_random_uuid(),
  "key"               VARCHAR(64) NOT NULL,
  "name"              VARCHAR(120) NOT NULL,
  "hypothesis"        VARCHAR(500),
  "surface"           VARCHAR(40) NOT NULL,
  "status"            VARCHAR(12) NOT NULL DEFAULT 'draft',
  "variants"          JSONB NOT NULL,
  "traffic_percent"   INTEGER NOT NULL DEFAULT 0,
  "guardrails"        JSONB NOT NULL,
  "start_at"          TIMESTAMPTZ,
  "end_at"            TIMESTAMPTZ,
  "started_at"        TIMESTAMPTZ,
  "stopped_at"        TIMESTAMPTZ,
  "stop_reason"       VARCHAR(300),
  "stopped_by_system" BOOLEAN NOT NULL DEFAULT false,
  "created_by"        UUID,
  "created_at"        TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updated_at"        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "experiments_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "experiments_status_chk" CHECK ("status" IN ('draft', 'running', 'stopped')),
  CONSTRAINT "experiments_traffic_chk" CHECK ("traffic_percent" BETWEEN 0 AND 100)
);
CREATE UNIQUE INDEX "experiments_key_key" ON "experiments"("key");
CREATE INDEX "experiments_status_idx" ON "experiments"("status");

CREATE TABLE "experiment_exposures" (
  "experiment_id" UUID NOT NULL,
  "unit_id"       VARCHAR(64) NOT NULL,
  "variant"       VARCHAR(32) NOT NULL,
  "first_at"      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "experiment_exposures_pkey" PRIMARY KEY ("experiment_id", "unit_id"),
  CONSTRAINT "experiment_exposures_experiment_id_fkey"
    FOREIGN KEY ("experiment_id") REFERENCES "experiments"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "experiment_exposures_experiment_id_variant_idx"
  ON "experiment_exposures"("experiment_id", "variant");

CREATE TABLE "experiment_results" (
  "id"                UUID NOT NULL DEFAULT gen_random_uuid(),
  "experiment_id"     UUID NOT NULL,
  "computed_at"       TIMESTAMPTZ NOT NULL DEFAULT now(),
  "srm_p"             DOUBLE PRECISION,
  "srm_flag"          BOOLEAN NOT NULL DEFAULT false,
  "guardrail_tripped" BOOLEAN NOT NULL DEFAULT false,
  "payload"           JSONB NOT NULL,
  CONSTRAINT "experiment_results_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "experiment_results_experiment_id_fkey"
    FOREIGN KEY ("experiment_id") REFERENCES "experiments"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "experiment_results_experiment_id_computed_at_idx"
  ON "experiment_results"("experiment_id", "computed_at" DESC);

-- ranking_events: native weekly RANGE partitions on created_at; the partition
-- key joins the primary key (PostgreSQL requires it). Nothing points at this
-- table, so there is no foreign-key problem. Rows outside every partition fall
-- into the DEFAULT partition, so a late maintenance job never loses a row.
CREATE TABLE "ranking_events" (
  "id"              BIGINT GENERATED BY DEFAULT AS IDENTITY,
  "created_at"      TIMESTAMPTZ NOT NULL DEFAULT now(),
  "kind"            VARCHAR(16) NOT NULL,
  "user_id"         UUID,
  "surface"         VARCHAR(40) NOT NULL,
  "item_id"         VARCHAR(64),
  "list_id"         VARCHAR(32),
  "position"        SMALLINT,
  "formula_version" VARCHAR(32),
  "experiment_key"  VARCHAR(64),
  "variant"         VARCHAR(32),
  "value"           INTEGER,
  "features"        JSONB,
  CONSTRAINT "ranking_events_pkey" PRIMARY KEY ("id", "created_at")
) PARTITION BY RANGE ("created_at");

CREATE INDEX "ranking_events_experiment_key_created_at_idx" ON "ranking_events"("experiment_key", "created_at");
CREATE INDEX "ranking_events_kind_created_at_idx" ON "ranking_events"("kind", "created_at");
CREATE INDEX "ranking_events_user_id_created_at_idx" ON "ranking_events"("user_id", "created_at");

CREATE TABLE "ranking_events_default" PARTITION OF "ranking_events" DEFAULT;

-- Creates the missing weekly partitions (Monday start, UTC) from last week to
-- p_weeks_ahead weeks ahead. SECURITY DEFINER: the application role cannot
-- create tables itself. Names: ranking_events_pYYYYMMDD (the Monday).
CREATE OR REPLACE FUNCTION lawbid_ranking_ensure_partitions(p_weeks_ahead integer DEFAULT 4)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
  v_w date := (date_trunc('week', now() AT TIME ZONE 'UTC') - interval '1 week')::date;
  v_last date := (date_trunc('week', now() AT TIME ZONE 'UTC') + make_interval(weeks => p_weeks_ahead))::date;
  v_created integer := 0;
  v_name text;
BEGIN
  WHILE v_w <= v_last LOOP
    v_name := 'ranking_events_p' || to_char(v_w, 'YYYYMMDD');
    IF to_regclass(format('public.%I', v_name)) IS NULL THEN
      BEGIN
        EXECUTE format(
          'CREATE TABLE public.%I PARTITION OF public.ranking_events FOR VALUES FROM (%L) TO (%L)',
          v_name,
          (v_w::timestamp AT TIME ZONE 'UTC'),
          ((v_w + 7)::timestamp AT TIME ZONE 'UTC'));
        v_created := v_created + 1;
      EXCEPTION WHEN check_violation THEN
        -- Rows of that week already sit in the DEFAULT partition.
        RAISE WARNING 'partition % not created: rows of that week are in the default partition', v_name;
      END;
    END IF;
    v_w := v_w + 7;
  END LOOP;
  RETURN v_created;
END
$fn$;

-- Retention: removes weekly partitions whose whole week is older than
-- p_keep_days days. Only partitions named by the function above are touched.
CREATE OR REPLACE FUNCTION lawbid_ranking_drop_old_partitions(p_keep_days integer DEFAULT 90)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
  r record;
  v_cut date := (now() AT TIME ZONE 'UTC')::date - p_keep_days;
  v_n integer := 0;
BEGIN
  IF p_keep_days < 7 THEN
    RAISE EXCEPTION 'retention below 7 days refused';
  END IF;
  FOR r IN
    SELECT c.relname AS name
      FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
     WHERE i.inhparent = to_regclass('public.ranking_events')
       AND c.relname ~ '^ranking_events_p[0-9]{8}$'
       AND to_date(right(c.relname, 8), 'YYYYMMDD') + 7 <= v_cut
  LOOP
    EXECUTE format('DROP TABLE public.%I', r.name);
    v_n := v_n + 1;
  END LOOP;
  -- The DEFAULT partition only holds late strays: trim it the same way.
  DELETE FROM public.ranking_events_default WHERE created_at < v_cut::timestamptz;
  RETURN v_n;
END
$fn$;

SELECT lawbid_ranking_ensure_partitions(4);

-- Append-only for the application role (it keeps INSERT / SELECT); old weeks
-- leave only through the definer function above.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'lawbid_app') THEN
    REVOKE ALL ON FUNCTION lawbid_ranking_ensure_partitions(integer) FROM PUBLIC;
    REVOKE ALL ON FUNCTION lawbid_ranking_drop_old_partitions(integer) FROM PUBLIC;
    GRANT EXECUTE ON FUNCTION lawbid_ranking_ensure_partitions(integer) TO lawbid_app;
    GRANT EXECUTE ON FUNCTION lawbid_ranking_drop_old_partitions(integer) TO lawbid_app;
    REVOKE UPDATE, DELETE, TRUNCATE ON "ranking_events" FROM lawbid_app;
  END IF;
END $$;
