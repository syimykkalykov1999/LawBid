#!/usr/bin/env node
// Prisma 7: the new `prisma-client` generator no longer ships `Prisma.dmmf`
// (the old `prisma-client-js` client did). The sharding router, the
// soft-delete extension and several schema-derived specs read the data model
// at runtime, so this generator writes the same `dmmf.datamodel` the old
// client carried into src/generated/prisma-dmmf.ts at `prisma generate`.
//
// Built on Prisma's own generator API (`@prisma/generator-helper`,
// `generatorHandler`, the interface every community generator uses, e.g.
// prisma-erd-generator, prisma-dbml-generator). The data is exactly what
// Prisma hands to every generator (`options.dmmf.datamodel`), nothing is
// derived by hand.
const { mkdirSync, writeFileSync } = require('node:fs');
const { dirname, join } = require('node:path');
const { generatorHandler } = require('@prisma/generator-helper');

generatorHandler({
  onManifest() {
    return { prettyName: 'LawBid DMMF', defaultOutput: '../src/generated' };
  },
  async onGenerate(options) {
    const dir = options.generator.output?.value;
    if (!dir) throw new Error('dmmf generator: output is required');
    const file = join(dir, 'prisma-dmmf.ts');
    mkdirSync(dirname(file), { recursive: true });
    const json = JSON.stringify(options.dmmf.datamodel);
    writeFileSync(
      file,
      [
        '/* !!! Generated by prisma/dmmf-generator.cjs at `prisma generate`. Do not edit. !!! */',
        '/* eslint-disable */',
        "import type { DMMF } from '@prisma/client/runtime/client';",
        '',
        '/** The schema data model, as `Prisma.dmmf.datamodel` was in Prisma 6. */',
        `export const datamodel: DMMF.Datamodel = JSON.parse(${JSON.stringify(json)});`,
        '',
      ].join('\n'),
    );
  },
});
